# ФУНКЦИИ РАБОТЫ С ЭМОДЗИ
# ═══════════════════════════════════════════════════════════════════════


def ce(name: str) -> str:
    """
    Рендерит кастомный эмодзи как HTML-тег <tg-emoji>.

    Работает в:
      ✅ Тексте сообщений (parse_mode="HTML")
      ✅ Тексте кнопок InlineKeyboard (parse_mode="HTML")

    НЕ работает в:
      ❌ Тексте кнопок ReplyKeyboard — используйте ce_fallback()
      ❌ callback.answer() — только обычный текст

    Ищет имя в INTERFACE_EMOJI и SERVICE_EMOJI (через CUSTOM_EMOJI).
    У юзеров с Premium видна анимированная иконка.
    У юзеров без Premium виден запасной Unicode-символ.
    Если имя не найдено — возвращает «❓».
    """
    entry = CUSTOM_EMOJI.get(name)
    if not entry:
        return "❓"

    emoji_id = entry.get("id", "")
    fallback = entry.get("fallback", "❓")

    if emoji_id:
        return f'<tg-emoji emoji-id="{emoji_id}">{fallback}</tg-emoji>'
    else:
        return fallback


def ce_fallback(name: str) -> str:
    """
    Возвращает только запасной Unicode-символ (без HTML-тега).

    Нужна для кнопок ReplyKeyboard (нижнее меню) — они НЕ поддерживают
    HTML-теги <tg-emoji>, Telegram рендерит их как сырой текст.
    """
    entry = CUSTOM_EMOJI.get(name)
    if not entry:
        return "❓"
    return entry.get("fallback", "❓")


def ce_id(name: str) -> str:
    """
    Возвращает только custom_emoji_id по имени (без запасного символа).
    Пустая строка, если имя не найдено или ID не задан.
    Нужна для параметра icon_custom_emoji_id у кнопок.
    """
    entry = CUSTOM_EMOJI.get(name, {})
    return entry.get("id", "")


def set_emoji_id(name: str, emoji_id: str):
    """Обновляет custom_emoji_id для существующего эмодзи во время выполнения."""
    if name in INTERFACE_EMOJI:
        INTERFACE_EMOJI[name]["id"] = emoji_id
    elif name in SERVICE_EMOJI:
        SERVICE_EMOJI[name]["id"] = emoji_id


def bulk_set_emoji_ids(mapping: dict[str, str]):
    """Массово устанавливает несколько custom_emoji_id за раз."""
    for name, emoji_id in mapping.items():
        set_emoji_id(name, emoji_id)
